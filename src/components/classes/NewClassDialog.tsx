import { useState } from "react";
import { Loader2 } from "lucide-react";
import { Dialog, DialogContent, DialogHeader, DialogTitle, DialogFooter } from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Switch } from "@/components/ui/switch";
import { toast } from "sonner";
import { createClass, type ClassRow } from "@/lib/classes";

interface Props {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  teacherId: string;
  onCreated: (cls: ClassRow) => void;
}

/** Create-class form (Google Classroom model): one subject, one group.
 *  The join code is generated by the database. */
export const NewClassDialog = ({ open, onOpenChange, teacherId, onCreated }: Props) => {
  const [title, setTitle] = useState("");
  const [subject, setSubject] = useState("");
  const [program, setProgram] = useState("");
  const [semester, setSemester] = useState("");
  const [section, setSection] = useState("");
  const [approval, setApproval] = useState(false);
  const [saving, setSaving] = useState(false);

  const submit = async () => {
    if (!title.trim()) {
      toast.error("Give your class a title first");
      return;
    }
    setSaving(true);
    try {
      const cls = await createClass(teacherId, {
        title,
        subject: subject || title,
        program,
        semester: semester ? Number(semester) : undefined,
        section,
        joinRequiresApproval: approval,
      });
      toast.success(`Class created — share code ${cls.code} with your students`);
      onCreated(cls);
      onOpenChange(false);
      setTitle(""); setSubject(""); setProgram(""); setSemester(""); setSection(""); setApproval(false);
    } catch (e: any) {
      toast.error(e?.message || "Could not create the class");
    } finally {
      setSaving(false);
    }
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="rounded-2xl max-w-md">
        <DialogHeader>
          <DialogTitle className="font-display">Create a Class</DialogTitle>
        </DialogHeader>
        <div className="space-y-3.5">
          <div className="space-y-1.5">
            <Label htmlFor="nc-title">Class title *</Label>
            <Input id="nc-title" placeholder="e.g. Discrete Structure" value={title} onChange={(e) => setTitle(e.target.value)} className="rounded-xl" />
          </div>
          <div className="space-y-1.5">
            <Label htmlFor="nc-subject">Subject (used for class tests)</Label>
            <Input id="nc-subject" placeholder="e.g. Digital Logic Design" value={subject} onChange={(e) => setSubject(e.target.value)} className="rounded-xl" />
          </div>
          <div className="grid grid-cols-3 gap-2.5">
            <div className="space-y-1.5">
              <Label htmlFor="nc-program">Program</Label>
              <Input id="nc-program" placeholder="BS SE" value={program} onChange={(e) => setProgram(e.target.value)} className="rounded-xl" />
            </div>
            <div className="space-y-1.5">
              <Label htmlFor="nc-sem">Semester</Label>
              <Input id="nc-sem" type="number" min={1} max={8} placeholder="1" value={semester} onChange={(e) => setSemester(e.target.value)} className="rounded-xl" />
            </div>
            <div className="space-y-1.5">
              <Label htmlFor="nc-sec">Section</Label>
              <Input id="nc-sec" placeholder="A" value={section} onChange={(e) => setSection(e.target.value)} className="rounded-xl" />
            </div>
          </div>
          <div className="flex items-center justify-between rounded-xl border border-border px-3 py-2.5">
            <div>
              <p className="text-sm font-medium">Approve students before they join</p>
              <p className="text-[11px] text-muted-foreground">Off = anyone with the code joins instantly</p>
            </div>
            <Switch checked={approval} onCheckedChange={setApproval} aria-label="Require join approval" />
          </div>
        </div>
        <DialogFooter>
          <Button variant="outline" className="rounded-xl" onClick={() => onOpenChange(false)}>Cancel</Button>
          <Button className="rounded-xl gradient-primary" onClick={submit} disabled={saving}>
            {saving && <Loader2 className="w-4 h-4 mr-1.5 animate-spin" />} Create Class
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
};

export default NewClassDialog;
